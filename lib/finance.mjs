/* Кредит: одна арифметика на весь сайт.
   Заказчик 2026-09-29: «на странице автомобилей написано лизинг и платёж от. сделай так чтобы там
   был не лизинг а кредит и платёж считают от цены машины на максимальный срок и участие клиента
   20%. в блок кредитный калькулятор добавь ползунок участие клиента от 5% до 80%».

   Отсюда три величины, которые обязаны совпадать в карточке автомобиля (сервер считает платёж при
   рендере) и в /kalkulyator (клиент пересчитывает при движении ползунков):
     • RATE_PERCENT   — ставка «под капотом»: 16 % годовых (поле «Ставка» убрано из формы);
     • MONTHS_MAX     — максимальный срок, он же верхняя граница ползунка «Срок, месяцев»;
     • SHARE_DEFAULT  — участие клиента по умолчанию: 20 % от цены, как в подписи карточки;
     • SHARE_MIN/MAX  — границы ползунка «Участие клиента, %».
   Формула — аннуитет; при нулевой сумме кредита платёж 0, а не деление на ноль. */

export const RATE_PERCENT = 16;
export const MONTHS_MAX = 84;
export const SHARE_DEFAULT = 20;
export const SHARE_MIN = 5;
export const SHARE_MAX = 80;

/* Показатель долговой нагрузки (ПДН) — заказчик 02.10.2026: «Найди эталонный вид блока расчёта по
   кредиту добавь туда какой доход должен быть у клиента чтобы получить этот кредит, методологию
   Какой должен быть доход клиента возьми с нормативных актов Беларуси где считается показатель
   долговой нагрузки, Наверное надо ещё значение Сколько у человека Уже есть платежи по кредитам
   чтобы он мог внести и показать налоговой нагрузки считался верным».

   Нормативка:
     • постановление Правления Национального банка от 31.03.2020 № 100 «О расчёте показателей
       долговой нагрузки и обеспеченности кредита» + разъяснение Нацбанка «О методике расчёта
       показателей долговой нагрузки» (nbrb.by/today/faq/o-metodike-rascheta-pokazatelej-dolgovoj-nagruzki):
       ПДН = сумма ежемесячных платежей физлица / среднемесячный доход × 100 %, допустимое значение —
       «ПДН не должен превышать 40 процентов»;
     • в сумму платежей входят платёж по выдаваемому кредиту, платежи по другим кредитным операциям,
       коммерческим займам, рассрочке, просроченная задолженность в полном объёме и обязательства
       поручителя — поэтому в форме есть поле «Платежи по другим кредитам»;
     • доход считается «за вычетом обязательных удержаний» — подоходный налог 13 % и взносы
       работающих граждан в ФСЗН 1 % (итого 14 %), поэтому доход до удержаний = доход / 0,86;
     • 50 % вместо 40 % разрешены только по кредитам на товары белорусского производства, «за
       исключением автотранспортных средств» (постановление Правления Нацбанка от 03.08.2026 № 185),
       так что для автомобиля предел остаётся 40 %.
   Здесь же границы полей «Доход в месяц» и «Платежи по другим кредитам»: их показывает сервер
   (lib/pages.mjs), а браузерный initCalc берёт те же числа из data-атрибутов формы. */
export const PDN_LIMIT_PERCENT = 40;
export const WITHHOLDING_PERCENT = 14;
export const INCOME_MIN = 400;
export const INCOME_MAX = 8000;
export const INCOME_STEP = 50;
/** Доход по умолчанию: 2 500 Б чистыми. При цене 60 000 Б, участии 20 % и сроке 84 мес. платёж
 *  выходит ≈ 953 Б, то есть нагрузка ≈ 38 % — пример по умолчанию проходит норматив 40 %. */
export const INCOME_DEFAULT = 2500;
export const OTHER_MAX = 3000;
export const OTHER_STEP = 50;
export const OTHER_DEFAULT = 0;

/** Показатель долговой нагрузки в процентах: все платежи к доходу «чистыми». */
export function debtBurden(payments, income) {
  const pay = Math.max(0, Number(payments) || 0);
  const inc = Math.max(0, Number(income) || 0);
  return inc > 0 ? (pay / inc) * 100 : 0;
}

/** Доход «чистыми», при котором все платежи укладываются в норматив ПДН (40 %). */
export function incomeForLimit(payments, limitPercent = PDN_LIMIT_PERCENT) {
  const pay = Math.max(0, Number(payments) || 0);
  const limit = limitPercent > 0 ? limitPercent : PDN_LIMIT_PERCENT;
  return pay / (limit / 100);
}

/** Тот же доход, но до обязательных удержаний: подоходный 13 % + ФСЗН 1 %. */
export function incomeBeforeTax(netIncome, withholdingPercent = WITHHOLDING_PERCENT) {
  return (Number(netIncome) || 0) / (1 - withholdingPercent / 100);
}

/** Ежемесячный платёж по аннуитету: сумма кредита, срок в месяцах, ставка в % годовых. */
export function monthlyPayment(credit, months, ratePercent = RATE_PERCENT) {
  const sum = Math.max(0, Number(credit) || 0);
  const n = Math.max(1, Math.round(Number(months) || 0));
  if (sum <= 0) return 0;
  const m = (Number(ratePercent) || 0) / 100 / 12;
  return m > 0 ? (sum * m) / (1 - Math.pow(1 + m, -n)) : sum / n;
}

/** Сумма кредита для цены автомобиля и участия клиента в процентах. */
export function creditFor(price, sharePercent = SHARE_DEFAULT) {
  return Math.max(0, Math.round(Number(price) || 0) * (1 - (Number(sharePercent) || 0) / 100));
}

/** Платёж карточки автомобиля: полная цена, максимальный срок, участие клиента 20 %. */
export function carPagePayment(price, sharePercent = SHARE_DEFAULT, months = MONTHS_MAX) {
  return Math.round(monthlyPayment(creditFor(price, sharePercent), months));
}
