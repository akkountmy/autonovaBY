export const OPTION_GROUPS = GROUP_IDS.map(([id, label, ids]) => ({ id, label, ids }));

const GROUP_BY_LABEL = new Map();
for (const g of OPTION_GROUPS) for (const id of g.ids) GROUP_BY_LABEL.set(id, g.id);
/* «Прочее» — не свалка, а честная группа для опций, которых нет в раскладке (например, добавят
   новую в CAR_OPTIONS и забудут здесь): лучше показать её одной строкой в конце, чем потерять. */
const GROUP_OF_ID = (id) => GROUP_BY_LABEL.get(id) || 'other';

/** Опции, разложенные по группам для блока «Комплектация»: пустые группы не возвращаются. */
export function groupOptions(values) {
  const list = normalizeOptions(values);
  const byId = new Map(CAR_OPTIONS.map((o) => [o.label, o.id]));
  const buckets = new Map(OPTION_GROUPS.map((g) => [g.id, []]));
  for (const label of list) buckets.get(GROUP_OF_ID(byId.get(label)))?.push(label);
  return OPTION_GROUPS
    .map((g) => ({ id: g.id, label: g.label, items: buckets.get(g.id) }))
    .filter((g) => g.items.length);
}

/** Текст комплектации для карточки и поиска: салон, название комплектации и её содержимое. */
export function composeEquipment({ trimName = '', interiorColor = '', interiorMaterial = '', options = [] } = {}) {
  const parts = [];
  const interior = interiorText(interiorColor, interiorMaterial);
  if (interior) parts.push(interior + '.');
  const name = String(trimName || '').trim();
  const list = normalizeOptions(options);
  if (name) parts.push(`Комплектация «${name}».`);
  if (list.length) parts.push(`В комплектацию входит: ${list.join(', ')}.`);
  return parts.join(' ');
}
