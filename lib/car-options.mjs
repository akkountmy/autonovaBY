/** Приводит присланные значения к порядку справочника и убирает повторы/мусор. */
export function normalizeOptions(values) {
  const set = new Set([].concat(values || []).map((v) => String(v).trim()).filter(Boolean));
  return CAR_OPTION_LABELS.filter((l) => set.has(l));
}

/** «Салон тёмный, искусственная кожа» — как в сиде (lib/seed.mjs: EQUIP_DEFAULT). */
export function interiorText(color, material) {
  const parts = [color, material].map((v) => String(v || '').trim()).filter(Boolean);
  if (!parts.length) return '';
  return 'Салон ' + parts.join(', ');
}

