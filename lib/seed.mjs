export function seedCars({ force = false } = {}) {
  const existing = num('SELECT COUNT(*) FROM cars');
  if (existing > 0 && !force) return { added: 0, skipped: existing };
  if (force) {
    db.exec('DELETE FROM car_photos; DELETE FROM cars;');
  }
  const cars = JSON.parse(fs.readFileSync(SEED, 'utf8'));
  let added = 0, n = 0;
  const insert = db.prepare(`INSERT INTO cars
    (slug, brand, model, generation, year, mileage, price, transmission, volume, fuel, body, drive,
     color, power, fuel_use, vin, description, equipment, status, is_new, featured, source_url, source_id, owner_id)
    VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,NULL)`);
  const photo = db.prepare('INSERT INTO car_photos (car_id, path, sort) VALUES (?,?,?)');
  for (const c of cars) {
    if (one('SELECT id FROM cars WHERE slug = ?', c.slug)) continue;
    const desc = c.description || `Автомобиль находится на площадке официального дилера «Автонова с пробегом», г. Гомель, ул. Мазурова, 112. ${SELLER_TEXT}`;
    const info = insert.run(
      c.slug, c.brand, c.model, c.generation || '', c.year, c.mileage, c.price,
      c.transmission, Number(c.volume) || 0, c.fuel, c.body, c.drive || 'fwd',
      c.color || '', c.power || 0, Number(c.fuel_use) || 0, c.vin || '',
      desc, c.equipment || EQUIP_DEFAULT, 'published', 0, c.featured ? 1 : 0,
      c.source_url || '', c.source_id || '',
    );
    const id = Number(info.lastInsertRowid);
    (c.photos || []).forEach((p, i) => photo.run(id, p, i));
    added++; n++;
  }
  /* «Новые поступления» — четыре самых свежих поступления (заказчик: «Сделай авто новый в 4
     карточках, и показывай в разделе только эти 4 карточки»). Раньше флаг выводился из года и
     пробега (2024+ и до 12 000 км) — помечались совсем другие машины, и раздел с плашкой не
     совпадал. Теперь флаг ставят тем, кто стоит в конце сида (они и попадают в базу последними,
     поэтому у них самый свежий created_at), — ровно то же состояние, что в рабочей базе. */
  run('UPDATE cars SET is_new = 0');
  run(`UPDATE cars SET is_new = 1 WHERE id IN (SELECT id FROM cars WHERE status='published' ORDER BY created_at DESC, id DESC LIMIT 4)`);
  return { added, total: n };
}

