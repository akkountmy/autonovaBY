// Спецпредложение «Горящая продажа»: кто в него входит — одно правило на весь сайт.
//
// Заказчик 2026-09-30: «с большей частью объявлений которые не задействованы в спецпрограммах
// удалить скидку». Значит, скидка остаётся ровно у машин спецпредложения — тех, что показаны в
// блоке «Горящая продажа» в герое главной (и на своей странице получают плашку «Горящая продажа»);
// у остальных объявлений ни плашки «Скидка −N руб.», ни зачёркнутого «было» быть не должно.
// Отбор живёт здесь одним куском SQL именно поэтому: его подставляют и блок на главной, и страница
// автомобиля (lib/pages.mjs: hotCars), и демонстрационное заполнение скидок (lib/db.mjs:
// backfillDiscounts) — «кто в спецпрограмме» не может разойтись между витриной и базой.
//
// Критерий прежний (lib/pages.mjs: hotCars, заказчик 2026-09-27 «добавь ещё на свой выбор две
// карточки из имеющихся авто» — было три, стало пять): опубликованные автомобили с настоящей ценой
// (price > 0) и хотя бы одним фото, по возрастанию цены. Первым ключом сортировки идёт featured:
// ниже на главной «Выбор дилера» показывает ровно четыре машины — и это ровно четыре самых дорогих
// авто с фото, — а без этого ключа третьей карточкой в герое встала бы самая дешёвая из них и один
// и тот же автомобиль стоял бы на главной дважды. Порядок детерминированный (цена, затем id).
// Цена должна быть настоящей: у машин «цена по запросу» (price = 0) и скидка, и зачёркнутая цена
// «до скидки» бессмысленны — от нуля их не посчитать.
export const SPECIAL_OFFER_LIMIT = 5;
export const SPECIAL_OFFER_WHERE = `c.status = 'published' AND c.price > 0
    AND (SELECT COUNT(*) FROM car_photos p WHERE p.car_id = c.id) > 0`;
export const SPECIAL_OFFER_ORDER = 'c.featured ASC, c.price ASC, c.id ASC';

/* Демонстрационная скидка спецпредложения: заказчик просил показывать в блоке скидку «например от
   2000 до 4000 руб.». Сумма детерминированная — по id (2 000 / 2 500 / 3 000 / 3 500 / 4 000):
   при каждом запуске у одной и той же машины одна и та же скидка, вёрстка и проверки не «дрожат».
   Формула нужна и в SQL (заполнение и разовая уборка лишних скидок в lib/db.mjs), и в коде
   (проверки, разборы), поэтому лежит здесь в двух видах — текстом для SQL и функцией. */
export const DEMO_DISCOUNT_SQL = '2000 + (id % 5) * 500';
export const demoDiscount = (id) => 2000 + (Number(id) % 5) * 500;
